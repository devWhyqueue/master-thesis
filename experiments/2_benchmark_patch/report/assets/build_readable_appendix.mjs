// Run with Node.js from any directory. Uses only the frozen, vendored tables.
// Original fragments remain the audit record; no inference is recomputed here.
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('./', import.meta.url));
const output = root + 'readable/';
mkdirSync(output, {recursive: true});
const read = name => readFileSync(root + 'tables/' + name + '.tex', 'utf8').split(/\r?\n/)
  .filter(line => /^(BRACS|TCGA-UT) & /.test(line))
  .map(line => line.replace(/\\\\\s*$/, '').split(' & ').map(cell => cell.trim()));
const write = (name, body) => writeFileSync(output + name + '.tex', '% Generated by assets/build_readable_appendix.mjs; do not edit.\n' + body + '\n');
const datasets = ['BRACS', 'TCGA-UT'];
const assignments = ['Native', 'Aligned', 'Reversed'];
const conditions = ['Moderate', 'Severe', 'Severe (spread)', 'Balanced'];
const short = {'Balanced': 'Patient shortage', 'Balanced (spread)': 'Balanced spread', 'Severe (spread)': 'Severe spread'};
const signals = ['Prevalence', 'Nominal support', 'Independent support', 'Difficulty', 'Diversity'];
const unique = values => [...new Set(values)];
const numbers = text => text.match(/-?\d+(?:\.\d+)?(?:e[+-]?\d+)?/gi)?.map(Number) ?? [];
const fmt = (value, digits = 1) => Number(value).toFixed(digits).replace(/^-0(?:\.0+)?$/, (0).toFixed(digits));
const range = (values, digits = 1, scale = 1) => {
  assert(values.length && values.every(Number.isFinite));
  const lo = fmt(Math.min(...values) * scale, digits), hi = fmt(Math.max(...values) * scale, digits);
  const number = text => `\\num{${text}}`;
  return lo === hi ? number(lo) : `${number(lo)} to ${number(hi)}`;
};
const row = cells => cells.join(' & ') + ' \\\\';
const table = (columns, header, rows) => `\\begin{tabular}{${columns}}\n\\toprule\n${row(header)}\n\\midrule\n${rows.map(row).join('\n')}\n\\bottomrule\n\\end{tabular}`;
const support = read('realized_support');
assert.equal(support.length, 102);
write('support', table('@{}lrrrr@{}', ['Allocation', 'Patients', 'Patches', '$\\rho$', '$1-H_{\\rm norm}$'],
  datasets.flatMap(dataset => [[`\\multicolumn{5}{@{}l}{\\textbf{${dataset}}}`], ...['Natural', 'Balanced', 'Balanced (spread)', ...conditions.slice(0, 3)].map(condition => {
    const rows = support.filter(r => r[0] === dataset && r[2] === condition);
    return [condition === 'Balanced' ? 'Balanced' : short[condition] ?? condition,
      range(rows.map(r => +r[4]), 0), range(rows.map(r => +r[6]), 0), range(rows.map(r => +r[7]), 3), range(rows.map(r => +r[8]), 4)];
  })])));
const tuning = read('tuning_selections');
assert.equal(tuning.length, 392);
assert(tuning.every(r => r[6] === 'No'));
for (const dataset of datasets) {
  const rows = tuning.filter(r => r[0] === dataset);
  write('tuning_' + dataset, table('@{}p{4.1cm}rrr@{}', ['Method', 'Learning rate', 'Strength', 'Zero strength'], unique(rows.map(r => r[3])).map(method => {
    const selected = rows.filter(r => r[3] === method);
    const rates = selected.map(r => r[4]).filter(v => v !== '---').map(Number);
    const controls = selected.map(r => r[5]).filter(v => v !== '---').map(Number);
    return [method, rates.length ? range(rates, 5) : 'Reused CE', controls.length ? range(controls, 4) : '---', controls.length ? `${controls.filter(v => v === 0).length}/${controls.length}` : '---'];
  })));
}
const damage = read('discrimination_deficit');
assert.equal(damage.length, 24);
assert.deepEqual(damage.filter(r => r[0] === 'TCGA-UT' && r[2] === 'Moderate').map(r => +r[3]), [0.0036, 0.0013, 0.0045]);
for (const [name, source, scale, digits] of [['damage', 'discrimination_deficit', 100, 2], ['calibration_damage', 'calibration_deficit', 1, 3]]) {
  write(name, table('@{}lllrl@{}', ['Dataset', 'Comparison', 'Assignment', 'Deficit [95\\% CI]', 'Eligible'], read(source).map(r =>
    [r[0], short[r[2]] ?? r[2], r[1], `${fmt(+r[3] * scale, digits)} [${numbers(r[4]).map(n => fmt(n * scale, digits)).join(', ')}]`, r[5] === 'Open' ? 'Yes' : r[5] === 'Below threshold' ? 'Below minimum' : 'Imprecise'])));
}
// Forest plot: paired intervals, shared scale, and dataset-specific thresholds.
let forest = '\\begin{tikzpicture}[x=0.30cm,y=0.47cm,font=\\footnotesize]\n';
for (const [index, dataset] of datasets.entries()) {
  const shift = index * 8.1;
  forest += `\\begin{scope}[xshift=${shift}cm]\n\\node[font=\\bfseries] at (8.5,1.2) {${dataset}};\n`;
  for (const tick of [0, 5, 10, 15]) forest += `\\draw[gray!25] (${tick},0.3)--(${tick},-12);\\node[below] at (${tick},-12) {${tick}};\n`;
  const threshold = index ? 1 : 1.443;
  forest += `\\draw[dashed,orange!85!black] (${threshold},0.3)--(${threshold},-12);\n`;
  for (const [i, condition] of conditions.entries()) for (const [j, assignment] of assignments.entries()) {
    const r = damage.find(r => r[0] === dataset && r[1] === assignment && r[2] === condition);
    const [lo, hi] = numbers(r[4]).map(v => v * 100), mean = +r[3] * 100, y = -(i * 3 + j);
    const color = ['blue!65!black', 'teal!75!black', 'violet!75!black'][j];
    forest += `\\draw[${color},thick] (${lo},${y})--(${hi},${y});\\draw[${color}] (${lo},${y - .12})--(${lo},${y + .12}) (${hi},${y - .12})--(${hi},${y + .12});\n`;
    forest += `\\draw[${color},fill=${r[5] === 'Open' ? color : 'white'}] (${mean},${y}) circle[radius=2pt];\n`;
    if (j === 1) forest += `\\node[anchor=east,align=right,text width=2.15cm] at (-1,${y}) {${short[condition] ?? condition}};\n`;
  }
  forest += '\\node[below] at (8,-13) {Balanced-accuracy loss (points)};\n\\end{scope}\n';
}
forest += '\\end{tikzpicture}';
write('damage_figure', forest);
const confirmatory = read('confirmatory');
assert.equal(confirmatory.length, 100);
for (const [name, source] of [['recovery', 'confirmatory'], ['calibration_recovery', 'calibration_recovery']]) {
  const sourceRows = read(source);
  for (const dataset of datasets) {
    const rows = [];
    for (const condition of conditions) for (const assignment of assignments) {
      const matches = sourceRows.filter(r => r[0] === dataset && r[1] === assignment && r[2] === condition);
      if (!matches.length) continue;
      assert.equal(matches.length, 5);
      rows.push([`\\shortstack[l]{${short[condition] ?? condition}\\\\${assignment}}`, ...signals.map(signal => {
        const r = matches.find(r => r[3] === signal);
        assert(r);
        return `\\shortstack{${fmt(+r[4] * 100)}\\\\{}[${numbers(r[5]).map(n => fmt(n * 100)).join(', ')}]\\\\$p=${r[7]}$}`;
      })]);
    }
    write(name + '_' + dataset, table('@{}lccccc@{}', ['Comparison', 'Prevalence', 'Nominal', 'Independent', 'Difficulty', 'Diversity'], rows));
  }
}
// Recovery overview: annotate unclipped values; color alone saturates at +/-100%.
let heat = '\\begin{tikzpicture}[x=1.90cm,y=0.48cm,font=\\small]\n';
for (const [d, dataset] of datasets.entries()) {
  const offset = d * 15;
  heat += `\\node[anchor=west,font=\\bfseries] at (-3.5,${1 - offset}) {${dataset}};\n`;
  ['Prevalence', 'Nominal', 'Independent', 'Difficulty', 'Diversity'].forEach((s, x) => {heat += `\\node[font=\\footnotesize] at (${x},${1 - offset}) {${s}};\n`;});
  for (const [c, condition] of conditions.entries()) for (const [a, assignment] of assignments.entries()) {
    const y = -offset - c * 3 - a;
    heat += `\\node[anchor=east] at (-.65,${y}) {${short[condition] ?? condition}: ${assignment.toLowerCase()}};\n`;
    signals.forEach((signal, x) => {
      const r = confirmatory.find(r => r[0] === dataset && r[1] === assignment && r[2] === condition && r[3] === signal);
      const value = r ? +r[4] * 100 : 0;
      const color = r ? `${value >= 0 ? 'teal' : 'orange'}!${Math.round(Math.min(Math.abs(value), 100) * .55)}!white` : 'gray!15';
      heat += `\\fill[${color}] (${x - .48},${y - .45}) rectangle (${x + .48},${y + .45});\\node at (${x},${y}) {${r ? fmt(value, 0) + (+r[7] < .05 ? '$^{*}$' : '') : '---'}};\n`;
    });
  }
}
write('recovery_figure', heat + '\\end{tikzpicture}');
for (const [name, endpoint, scale, digits] of [['matched_damage', 'Discrimination', 100, 2], ['matched_calibration', 'Calibration', 1, 3]])
  write(name, table('@{}lllp{2.2cm}rl@{}', ['Dataset', 'Comparison', 'Assignment', 'Matched signal', 'Contrast [95\\% CI]', 'Holm $p$'], read('matched_contrast').filter(r => r[3] === endpoint && r[5] !== '---').map(r =>
    [r[0], short[r[2]] ?? r[2], r[1], r[4], `${fmt(+r[5] * scale, digits)} [${numbers(r[6]).map(v => fmt(v * scale, digits)).join(', ')}]`, r[7]])));
write('matched_beta', table('@{}lllrrrr@{}', ['Dataset', 'Comparison', 'Assignment', 'CE', 'Independent', 'Matched $\\beta$', 'Nominal'], read('matched_beta').map(r =>
  [r[0], short[r[2]] ?? r[2], r[1], ...r.slice(3).map(v => fmt(+v * 100))])));
// Wider roster: ranges across eligible assignment-level estimates, not intervals.
const roster = read('roster_recovery');
for (const dataset of datasets) {
  const rows = roster.filter(r => r[0] === dataset);
  write('roster_' + dataset, table('@{}p{4cm}rrrr@{}', ['Method', 'Moderate', 'Severe', 'Severe spread', 'Patient shortage'], unique(rows.map(r => r[4])).map(method =>
    [method, ...conditions.map(condition => {
      const group = rows.filter(r => r[2] === condition && r[3] === 'Discrimination' && r[4] === method);
      return group.length ? range(group.map(r => +r[5]), 0, 100) : '---';
    })])));
}
// Tier recall preserves all assignments and all reported tiers without class-row duplication.
const tiers = read('tier_endpoints');
assert.equal(tiers.length, 72);
for (const dataset of datasets) write('tiers_' + dataset, table('@{}llrrrr@{}', ['Assignment', 'Tier', 'Balanced spread', 'Moderate', 'Severe', 'Severe spread'],
  assignments.flatMap(assignment => ['head', 'body', 'tail'].map(tier => [assignment, tier, ...['Balanced (spread)', ...conditions.slice(0, 3)].map(condition => {
    const r = tiers.find(r => r[0] === dataset && r[1] === assignment && r[2] === condition && r[3] === tier);
    assert(r); return fmt(+r[4] * 100);
  })]))));
const calibration = read('calibration_detail');
write('calibration', table('@{}lllrrrr@{}', ['Dataset', 'Assignment', 'Condition', 'Raw NLL', 'Scaled NLL', 'Raw ECE', 'Scaled ECE'],
  calibration.filter(r => r[3] === 'CE').map(r => [r[0], r[1], short[r[2]] ?? r[2], r[4], r[7], numbers(r[6])[0].toFixed(3), r[9]])));
const costs = read('cost');
assert(costs.every(r => ['Accelerator hours', 'Peak memory (bytes)', 'Processed examples', 'Parameters', 'Unique exposures'].includes(r[4])));
for (const dataset of datasets) {
  const rows = costs.filter(r => r[0] === dataset);
  write('cost_' + dataset, table('@{}>{\\raggedright\\arraybackslash}p{3.8cm}rrrrr@{}', ['Method', 'Minutes', 'MiB', 'Examples', 'Unique', 'Parameters'], unique(rows.map(r => r[3])).map(method =>
    [method, ...[['Accelerator hours', 60, 1], ['Peak memory (bytes)', 1 / 1048576, 1], ['Processed examples', 1, 0], ['Unique exposures', 1, 0], ['Parameters', 1, 0]].map(([endpoint, scale, digits]) =>
      range(rows.filter(r => r[3] === method && r[4] === endpoint).map(r => +r[5]), digits, scale))])));
}
// Preserve all partition values, removing redundant average and severity columns.
for (const [name, endpoint, scale, digits] of [['split_damage', 'Discrimination', 100, 2], ['split_calibration', 'Calibration', 1, 3]])
  write(name, table('@{}lllrrr@{}', ['Dataset', 'Comparison', 'Assignment', 'Partition 1', 'Partition 2', 'Partition 3'], read('per_split').filter(r => r[3] === endpoint).map(r =>
    [r[0], short[r[2]] ?? r[2], r[1], ...r.slice(4, 7).map(v => fmt(+v * scale, digits))])));
console.log('Readable appendix generated; source counts, eligibility cells, and TCGA-UT moderate estimates checked.');
